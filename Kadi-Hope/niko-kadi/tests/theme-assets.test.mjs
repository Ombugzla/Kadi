import assert from 'node:assert/strict';
import { accessSync, readFileSync } from 'node:fs';
import { test } from 'node:test';

test('shared theme assets, typography, and backgrounds are included in the offline cache', () => {
  const image = new URL('../www/img/misty-mountains.webp', import.meta.url);
  const homeImage = new URL('../www/img/misty-mountains-home.webp', import.meta.url);
  const nikoPanel = new URL('../www/img/home-game-niko.webp', import.meta.url);
  const sequencePanel = new URL('../www/img/home-game-sequence.webp', import.meta.url);
  const styles = readFileSync(new URL('../www/css/base.css', import.meta.url), 'utf8');
  const homeStyles = readFileSync(new URL('../www/css/home.css', import.meta.url), 'utf8');
  const tableStyles = readFileSync(new URL('../www/css/table.css', import.meta.url), 'utf8');
  const chatStyles = readFileSync(new URL('../www/css/chat.css', import.meta.url), 'utf8');
  const screens = readFileSync(new URL('../www/js/screens.js', import.meta.url), 'utf8');
  const serviceWorker = readFileSync(new URL('../www/sw.js', import.meta.url), 'utf8');

  assert.doesNotThrow(() => accessSync(image));
  assert.doesNotThrow(() => accessSync(homeImage));
  assert.doesNotThrow(() => accessSync(nikoPanel));
  assert.doesNotThrow(() => accessSync(sequencePanel));
  assert.match(styles, /misty-mountains\.webp/);
  assert.doesNotMatch(styles, /home-layout\.webp/);
  assert.match(styles, /#app\.home-screen #homePage h1/);
  assert.doesNotMatch(styles, /#screen h1/);
  assert.match(styles, /source-sans-3\.woff/);
  assert.match(styles, /crimson-text-bold\.woff/);
  assert.match(styles, /--serif:\s*"Crimson Text"/);
  assert.match(styles, /--sans:\s*"Source Sans 3"/);
  assert.match(styles, /--app-backdrop:[^;]*misty-mountains\.webp/);
  assert.match(styles, /body\[data-mode="dark"\][\s\S]*?--app-backdrop:[^;]*misty-mountains\.webp/);
  assert.match(homeStyles, /gem\.svg/);
  assert.match(homeStyles, /gem-end\.svg/);
  assert.match(homeStyles, /home-game-niko\.webp/);
  assert.match(homeStyles, /home-game-sequence\.webp/);
  assert.match(homeStyles, /body\[data-mode="dark"\] #homePage \.game\.nk/);
  assert.match(tableStyles, /misty-mountains-home\.webp/);
  assert.match(tableStyles, /\.plate \.nm b \{ font-family: var\(--serif\); \}/);
  assert.match(chatStyles, /background-image: var\(--app-backdrop\)/);
  assert.match(chatStyles, /\.chat-peer b[^}]*var\(--serif\)/);
  assert.match(chatStyles, /\.chat-thread\[data-wall="felt"\]/);
  assert.match(screens, /h\.slice\(0, 4\)/);
  assert.match(serviceWorker, /'img\/misty-mountains\.webp'/);
  assert.match(serviceWorker, /'img\/misty-mountains-home\.webp'/);
  assert.match(serviceWorker, /'img\/home-game-niko\.webp'/);
  assert.match(serviceWorker, /'img\/home-game-sequence\.webp'/);
  assert.match(serviceWorker, /'fonts\/source-sans-3\.woff'/);
  assert.match(serviceWorker, /'fonts\/crimson-text-bold\.woff'/);
  assert.match(serviceWorker, /'fonts\/crimson-text-semibold\.woff'/);
  assert.match(serviceWorker, /niko-kadi-v65/);
});
